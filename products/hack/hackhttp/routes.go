	mux.Handle("POST /v1/hack/events/{slug}/checklist/not-needed/{item}", wrap(h.setChecklistNotNeeded))
	mux.Handle("DELETE /v1/hack/events/{slug}/checklist/not-needed/{item}", wrap(h.setChecklistNotNeeded))
