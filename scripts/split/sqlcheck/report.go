package main

import (
	"fmt"
	"strings"
)

var headings = []string{"SQL that names a Hack object", "SQL built at run time that names a Hack object", "Embedded .sql files outside db/ that name a Hack object", "Cannot evaluate: SQL built at run time from non-constant parts", "Same word as a platform column, for a person to confirm", "Not SQL: Go lists that name Hack tables or columns", "Other text"}

func truncate(s string, n int) string {
	r := []rune(s)
	if len(r) > n {
		return string(r[:n]) + "…"
	}
	return s
}
func collapsed(s string, n int) string { return truncate(strings.Join(strings.Fields(s), " "), n) }
func render(r scanResult, o options) string {
	var b strings.Builder
	fmt.Fprintln(&b, "# Generated by go run ./scripts/split/sqlcheck -warn")
	fmt.Fprintf(&b, "# Flags: -tests=%t -prose=%t -warn=%t -schema=%s -report=%s\n# Objects: %s\n", o.Tests, o.Prose, o.Warn, o.Schema, o.Report, o.Objects)
	fmt.Fprintln(&b, "# Line numbers move when files are edited; regenerate this file, do not hand-edit it.")
	for i, h := range headings {
		count := len(r.Sections[i])
		if i == 6 {
			for _, n := range r.ProseCounts {
				count += n
			}
		}
		fmt.Fprintf(&b, "\n%d. %s (%d)\n", i+1, h, count)
		for _, f := range r.Sections[i] {
			names := strings.Join(f.Names, ", ")
			if len(f.NameLines) > 0 {
				names += " (name lines: " + lineNumbers(f.NameLines) + ")"
			}
			limit := 160
			if i == 3 {
				limit = 140
				names = "non-constant: " + strings.Join(f.Operands, ", ")
			}
			fmt.Fprintf(&b, "%s:%d | %s | %s | %s\n", f.File, f.Line, f.Decl, names, collapsed(f.Text, limit))
			if len(f.Parts) > 0 {
				fmt.Fprintf(&b, "    built from: %s\n", strings.Join(f.Parts, "; "))
			}
		}
		if i == 6 {
			for _, n := range sortedKeys(r.ProseCounts) {
				fmt.Fprintf(&b, "%s: %d other-text strings (use -prose to list)\n", n, r.ProseCounts[n])
			}
		}
	}
	return b.String()
}
func scanCode(r scanResult, warn bool) int {
	if !warn && len(r.Sections[0])+len(r.Sections[1])+len(r.Sections[2]) > 0 {
		return 1
	}
	return 0
}
