#!/usr/bin/env python3
"""Build (and optionally publish) the Simple Hack UX atlas.

    python3 docs/ux-atlas/build.py            # build into docs/ux-atlas/dist/
    python3 docs/ux-atlas/build.py --publish  # build, then publish to the atlas site

What it does:
  * writes prototype/nav.js from spec.json (sidebar items per role, sample events),
    so the clickable prototype always matches the spec;
  * writes prototype/files.json (every prototype view, for the atlas viewer);
  * checks that every feature in features.json is placed on a screen and that every
    screen named in spec.json has a prototype file;
  * copies today's production screenshots from $ATLAS_TODAY
    (default /home/ubuntu/simple-hack-ux-atlas-today) into dist/today/.
"""
import json, os, shutil, sys, tarfile, io, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
PROTO = os.path.join(HERE, "prototype")
DIST = os.path.join(HERE, "dist")
TODAY = os.environ.get("ATLAS_TODAY", "/home/ubuntu/simple-hack-ux-atlas-today")
SITE = "simple-hack-ux-atlas"


def load(name):
    with open(os.path.join(HERE, name)) as f:
        return json.load(f)


def main():
    spec, feats = load("spec.json"), load("features.json")
    nav = {r["id"]: r.get("nav", []) for r in spec.get("roles", []) if r.get("nav")}
    events = spec.get("sample_events", [])
    with open(os.path.join(PROTO, "nav.js"), "w") as f:
        f.write("/* generated by build.py from spec.json; do not edit */\nwindow.PROTO = ")
        json.dump({"events": events, "nav": nav}, f, indent=1)
        f.write(";\n")

    files = sorted(n for n in os.listdir(PROTO) if n.endswith(".html") and n != "kit.html")
    with open(os.path.join(PROTO, "files.json"), "w") as f:
        json.dump(files, f, indent=0)

    screens = spec.get("screens", []) + spec.get("public_pages", [])
    placed = {fid for s in screens for fid in s.get("features", [])}
    unplaced = [x["id"] for x in feats if x["id"] not in placed]
    unknown = sorted(placed - {x["id"] for x in feats})
    noproto = [s["id"] for s in screens if s["id"] + ".html" not in files]
    print(f"{len(screens)} screens, {len(files)} prototype views, {len(feats)} features")
    for label, xs in (("features with no screen", unplaced), ("screens list unknown features", unknown),
                      ("screens with no prototype", noproto)):
        if xs:
            print(f"  {label}: {len(xs)}: {', '.join(xs[:20])}{' …' if len(xs) > 20 else ''}")

    shutil.rmtree(DIST, ignore_errors=True)
    os.makedirs(DIST)
    for n in ("index.html", "spec.json", "features.json", "changelog.json"):
        if os.path.exists(os.path.join(HERE, n)):
            shutil.copy(os.path.join(HERE, n), DIST)
    shutil.copytree(PROTO, os.path.join(DIST, "prototype"))
    if os.path.isdir(TODAY):
        shutil.copytree(TODAY, os.path.join(DIST, "today"))
    else:
        print(f"  warning: no screenshots at {TODAY}; the Today pictures will be missing")

    if "--publish" in sys.argv:
        publish()


def publish():
    cfg = json.load(open(os.path.expanduser("~/.website-deploy/config.json")))
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as t:
        for root, _, names in os.walk(DIST):
            for n in names:
                p = os.path.join(root, n)
                t.add(p, arcname=os.path.relpath(p, DIST))
    req = urllib.request.Request(
        cfg["base_url"].rstrip("/") + f"/v1/sites/{SITE}?create=1", data=buf.getvalue(), method="PUT",
        headers={"X-API-Key": cfg["api_key"], "X-Skill-Version": "0.27.18", "Content-Type": "application/gzip"})
    d = json.load(urllib.request.urlopen(req, timeout=300))
    print("published version", d.get("active_version"), d.get("site_url"))


if __name__ == "__main__":
    main()
